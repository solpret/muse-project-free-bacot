EP = "https://bsc.nodereal.io/"

def sel(sig):
    k = keccak.new(digest_bits=256); k.update(sig.encode())
    return "0x" + k.hexdigest()[:8]
def enc_addr(a): return a.lower().replace("0x", "").rjust(64, "0")
def calldata(fn):
    if fn.endswith("(address)"):
        return sel(fn) + enc_addr(USER)
    return sel(fn)

